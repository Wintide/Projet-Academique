CREATE TABLE Signalements (
    signalementID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pseudo_signaleur VARCHAR2(100) NOT NULL,
    utilisateur_cibleID NUMBER,
    videoID NUMBER,
    liveID NUMBER,
    commentaire_videoID NUMBER,
    commentaire_liveID NUMBER,
    raison CLOB NOT NULL,
    date_signalement TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    statut VARCHAR2(20) DEFAULT 'en attente' NOT NULL,
    moderateurID NUMBER,
    CONSTRAINT chk_statut_signalement CHECK (statut IN ('enattente', 'traite', 'rejete')),
    CONSTRAINT fk_pseudo_signaleur FOREIGN KEY (pseudo_signaleur) REFERENCES Utilisateurs(pseudo) ON DELETE CASCADE,
    CONSTRAINT fk_utilisateur_cibleID FOREIGN KEY (utilisateur_cibleID) REFERENCES Utilisateurs(utilisateurID) ON DELETE CASCADE,
    CONSTRAINT fk_videoID FOREIGN KEY (videoID) REFERENCES Videos(videoID) ON DELETE CASCADE,
    CONSTRAINT fk_liveID FOREIGN KEY (liveID) REFERENCES Lives(liveID) ON DELETE CASCADE,
    CONSTRAINT fk_commentaire_videoID FOREIGN KEY (commentaire_videoID) REFERENCES CommentairesVideos(commentaireID) ON DELETE CASCADE,
    CONSTRAINT fk_commentaire_liveID FOREIGN KEY (commentaire_liveID) REFERENCES CommentairesLives(commentaireID) ON DELETE CASCADE,
    CONSTRAINT fk_moderateurID_Signalement FOREIGN KEY (moderateurID) REFERENCES Moderateur(moderateurID) ON DELETE SET NULL,
    CONSTRAINT chk_signalement CHECK (
        (utilisateur_cibleID IS NOT NULL AND videoID IS NULL AND commentaire_videoID IS NULL AND liveID IS NULL AND commentaire_liveID IS NULL) OR 
        (videoID IS NOT NULL AND utilisateur_cibleID IS NULL AND commentaire_videoID IS NULL AND liveID IS NULL AND commentaire_liveID IS NULL) OR  
        (liveID IS NOT NULL AND utilisateur_cibleID IS NULL AND commentaire_videoID IS NULL AND videoID IS NULL AND commentaire_liveID IS NULL) OR
        (commentaire_videoID IS NOT NULL AND utilisateur_cibleID IS NULL AND videoID IS NULL AND liveID IS NULL AND commentaire_liveID IS NULL) OR
	(commentaire_liveID IS NOT NULL AND utilisateur_cibleID IS NULL AND videoID IS NULL AND liveID IS NULL AND commentaire_videoID IS NULL)
    )
);

