-- Vue des utilisateurs sur les interactions d'une vidéo publique
CREATE VIEW VueInteractions_VideosPubliques AS
SELECT v.titre, v.url_video, v.date_publication, v.vues,
       COUNT(CASE WHEN i.type_interaction = 'like' THEN 1 END) AS nb_likes,
       COUNT(CASE WHEN i.type_interaction = 'dislike' THEN 1 END) AS nb_dislikes,
       COUNT(c.commentaireID) AS nb_commentaires
FROM Videos v, Interactions i, CommentairesVideos c
WHERE v.videoID = i.videoID AND v.videoID = c.videoID AND v.visibilite = 'publique'
GROUP BY v.videoID, v.titre, v.url_video, v.date_publication, v.vues;

-- Vue des utilisateurs sur les interactions d'une vidéo privée
CREATE VIEW VueInteractions_VideosPrivees AS
SELECT v.titre, v.url_video, v.date_publication, v.vues,
       COUNT(CASE WHEN i.type_interaction = 'like' THEN 1 END) AS nb_likes,
       COUNT(CASE WHEN i.type_interaction = 'dislike' THEN 1 END) AS nb_dislikes
FROM Videos v, Interactions i, Utilisateurs u
WHERE v.videoID = i.videoID AND v.visibilite = 'privée' AND u.pseudo = USER
GROUP BY v.videoID, v.titre, v.url_video, v.date_publication, v.vues;

-- Vue des utilisateurs sur les interactions d'un commentaire vidéo
CREATE VIEW VueInteractions_Commentaires AS
SELECT v.titre, v.url_video, v.date_publication, c.contenu,
       COUNT(CASE WHEN i.type_interaction = 'like' THEN 1 END) AS nb_likes,
       COUNT(CASE WHEN i.type_interaction = 'dislike' THEN 1 END) AS nb_dislikes
FROM Videos v, CommentairesVideos c, Interactions i
WHERE v.videoID = c.videoID AND c.commentaireID = i.commentaireID AND v.visibilite = 'publique'
GROUP BY c.commentaireID, v.titre, v.url_video, v.date_publication, c.contenu;

-- Vue des moderateurs sur les videos
