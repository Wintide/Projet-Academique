-- Trigger pour mettre a jour le nomnre d'abonné d'un utilisateur
CREATE OR REPLACE TRIGGER Augmenter_Nb_Abonnes
AFTER INSERT ON Abonnements
FOR EACH ROW
BEGIN
    -- Augmenter le nombre d'abonnés de l'utilisateur
    UPDATE Utilisateurs
    SET nb_abonné = nb_abonné + 1
    WHERE utilisateurID = :NEW.abonnementID;
END;
/

