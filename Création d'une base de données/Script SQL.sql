CREATE TABLE Follow (
    followID NUMBER NOT NULL,
    followerID NUMBER NOT NULL,
    date_follow TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_follow PRIMARY KEY (followID, followerID),
    CONSTRAINT fk_followID FOREIGN KEY (followID) REFERENCES Utilisateurs(utilisateurID) ON DELETE CASCADE,
    CONSTRAINT fk_followerID FOREIGN KEY (followerID) REFERENCES Utilisateurs(utilisateurID) ON DELETE CASCADE
);

CREATE TABLE Interactions (
    interactionID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_interaction VARCHAR2(20) NOT NULL,
    utilisateurID NUMBER NOT NULL,
    videoID NUMBER,
    commentaireID NUMBER,
    date_interaction TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_type_interaction CHECK (type_interaction IN ('like', 'dislike')),
    CONSTRAINT fk_utilisateurID_Interactions FOREIGN KEY (utilisateurID) REFERENCES Utilisateurs(utilisateurID) ON DELETE CASCADE,
    CONSTRAINT fk_videoID_Interactions FOREIGN KEY (videoID) REFERENCES Videos(videoID) ON DELETE CASCADE,
    CONSTRAINT fk_commentaireID_Interactions FOREIGN KEY (commentaireID) REFERENCES CommentairesVideos(commentaireID) ON DELETE CASCADE,
    CONSTRAINT chk_interaction CHECK (
        (videoID IS NOT NULL AND commentaireID IS NULL) OR 
