-- Creation des tables
CREATE TABLE Utilisateurs (
    utilisateurID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 
    pseudo VARCHAR2(50) DEFAULT USER NOT NULL UNIQUE, 
    email VARCHAR2(50) NOT NULL UNIQUE,  
    date_inscription TIMESTAMP DEFAULT CURRENT_TIMESTAMP, 
    telephone VARCHAR2(20), 
    avatar_url VARCHAR2(255), 
    statut VARCHAR2(20) DEFAULT 'actif', 
    pays VARCHAR2(50) NOT NULL, 
    nb_abonné NUMBER DEFAULT 0 NOT NULL, 
    nb_follower NUMBER DEFAULT 0 NOT NULL,
    CONSTRAINT chk_statut CHECK (statut IN ('actif', 'suspendu', 'supprimé')) 
);

CREATE TABLE Categories(
    categorieID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 
    nom_categorie VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE Videos (
    videoID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre VARCHAR2(255) NOT NULL,
    description CLOB,
    url_video VARCHAR2(255) NOT NULL UNIQUE,
    date_publication TIMESTAMP,
    utilisateurID NUMBER NOT NULL,
    categorieID NUMBER,
    monetisation NUMBER(1) DEFAULT 0,
    vues NUMBER DEFAULT 0,
    visibilite VARCHAR2(20) DEFAULT 'publique',
    CONSTRAINT chk_visibilite_Videos CHECK (visibilite IN ('publique', 'privée')),
    CONSTRAINT fk_utilisateurID_Videos FOREIGN KEY (utilisateurID) REFERENCES Utilisateurs(utilisateurID) ON DELETE CASCADE,
    CONSTRAINT fk_categorieID_Videos FOREIGN KEY (categorieID) REFERENCES Categories(categorieID) ON DELETE SET NULL
);

CREATE TABLE Lives (
    liveID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre VARCHAR2(255) NOT NULL,
    description CLOB,
    url_live VARCHAR2(255) NOT NULL UNIQUE,
    date_debut TIMESTAMP NOT NULL,
    date_fin TIMESTAMP,
    utilisateurID NUMBER NOT NULL,
    categorieID NUMBER,
    statut VARCHAR2(20) DEFAULT 'programme' NOT NULL,
    CONSTRAINT chk_statut_live CHECK (statut IN ('encours', 'termine', 'programme')),
    CONSTRAINT fk_utilisateurID_Lives FOREIGN KEY (utilisateurID) REFERENCES Utilisateurs(utilisateurID) ON DELETE CASCADE,
    CONSTRAINT fk_categorieID_Lives FOREIGN KEY (categorieID) REFERENCES Categories(categorieID) ON DELETE SET NULL
);

CREATE TABLE Tags (
    tagID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom_tag VARCHAR2(50) NOT NULL UNIQUE
);

CREATE TABLE VideosTags (
    videoID NUMBER NOT NULL,
    tagID NUMBER NOT NULL,
    PRIMARY KEY (videoID, tagID),
    CONSTRAINT fk_videoID_VideoTag FOREIGN KEY (videoID) REFERENCES Videos(videoID) ON DELETE CASCADE,
    CONSTRAINT fk_tagID_VideoTag FOREIGN KEY (tagID) REFERENCES Tags(tagID) ON DELETE CASCADE
);


CREATE TABLE LivesTags (
    liveID NUMBER NOT NULL,
    tagID NUMBER NOT NULL,
    PRIMARY KEY (liveID, tagID),
    CONSTRAINT fk_liveID_LiveTag FOREIGN KEY (liveID) REFERENCES Lives(liveID) ON DELETE CASCADE,
    CONSTRAINT fk_tagID_LiveTag FOREIGN KEY (tagID) REFERENCES Tags(tagID) ON DELETE CASCADE
);

CREATE TABLE CommentairesVideos (
    commentaireID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commentaire_parentID NUMBER,
    contenu VARCHAR2(255),
    date_commentaire TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    utilisateurID NUMBER NOT NULL,
    videoID NUMBER NOT NULL,
    CONSTRAINT fk_commentaire_video_parentID FOREIGN KEY (commentaire_parentID) REFERENCES CommentairesVideos(commentaireID) ON DELETE CASCADE,
    CONSTRAINT fk_utilisateurID_commentaireVideo FOREIGN KEY (utilisateurID) REFERENCES Utilisateurs(utilisateurID) ON DELETE CASCADE,
    CONSTRAINT fk_videoID_commentaire FOREIGN KEY (videoID) REFERENCES Videos(videoID) ON DELETE CASCADE
);

CREATE TABLE CommentairesLives (
    commentaireID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commentaire_parentID NUMBER,
    contenu VARCHAR2(255),
    date_commentaire TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    utilisateurID NUMBER NOT NULL,
    liveID NUMBER NOT NULL,
    CONSTRAINT fk_commentaire_live_parentID FOREIGN KEY (commentaire_parentID) REFERENCES CommentairesLives(commentaireID) ON DELETE CASCADE,
    CONSTRAINT fk_utilisateurID_commentaireLive FOREIGN KEY (utilisateurID) REFERENCES Utilisateurs(utilisateurID) ON DELETE CASCADE,
    CONSTRAINT fk_liveID_commentaire FOREIGN KEY (liveID) REFERENCES Lives(liveID) ON DELETE CASCADE
);

CREATE TABLE Abonnements (
    abonnementID NUMBER NOT NULL,
    abonneID NUMBER NOT NULL,
    date_abonnement TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    statut VARCHAR2(20) DEFAULT 'actif',
