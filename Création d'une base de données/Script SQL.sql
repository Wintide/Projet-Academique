-- Création des vues

-- Vue d'un utilisateurs sur les autres utilisateurs
CREATE VIEW VueUtilisateurs_AutresUtilisateurs AS
SELECT pseudo, nb_abonné, date_inscription, statut
FROM Utilisateurs
WHERE pseudo != USER;

-- Vue d'un utilisateurs sur lui même 
CREATE VIEW VueUtilisateurs_Utilisateur AS
SELECT u.utilisateurID, pseudo, email, date_inscription, telephone, avatar_url, u.statut AS Statut_du_Compte, pays, nb_abonné, nb_follower, r.montant_total AS revenue, p.date_fin AS expiration_prenium
FROM Utilisateurs u, Revenus r, Preniums p
WHERE u.utilisateurID = r.utilisateurID AND u.utilisateurID = p.utilisateurID AND pseudo = USER;

-- Vue des utilisateurs sur les autres vidéos publiques
CREATE VIEW VueVideos_VideosPubliquesAutresUtilisateurs AS
SELECT v.titre, v.description, v.url_video, v.date_publication, v.vues, c.nom_categorie, u.pseudo, t.nom_tag
FROM Utilisateurs u, Videos v, VideosTags vt, Tags t, Categories c
WHERE u.utilisateurID = v.utilisateurID AND v.videoID = vt.videoID AND t.tagID = vt.tagID AND v.categorieID = c.categorieID AND v.visibilite = 'publique' AND u.pseudo != USER;

