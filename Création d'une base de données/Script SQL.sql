-- Creation des triggers

-- Trigger pour mettre a jour le montant du revenus après d'une insertion sur la table Dons
CREATE OR REPLACE TRIGGER MAJ_Revenus_Dons
AFTER INSERT ON Dons
FOR EACH ROW
BEGIN
    -- Mise à jour des revenus avec le montant du don
    UPDATE Revenus
    SET montant_total = montant_total + :NEW.montant
    WHERE utilisateurID = (SELECT utilisateurID FROM Lives WHERE liveID = :NEW.liveID);
    -- Mise a jour de la date
    UPDATE Revenus
    SET dernière_maj = CURRENT_TIMESTAMP
    WHERE utilisateurID = (SELECT utilisateurID FROM Lives WHERE liveID = :NEW.liveID);
END;
/

-- Trigger pour mettre a jour le montant du revenus après d'une insertion sur la table Videos (monetisation)
CREATE OR REPLACE TRIGGER MAJ_Revenus_Videos
