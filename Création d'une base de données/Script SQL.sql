-- Vue des modérateurs sur les signalements d'une chaine/d'un utilisateur
CREATE VIEW VueModo_Signalement_Chaine AS
SELECT u.pseudo AS Personne_Signalée, s.raison, s.date_signalement, s.statut, s.pseudo_signaleur AS Signaleur
FROM Signalements s, Utilisateurs u
WHERE s.utilisateur_cibleID IS NOT NULL and s.utilisateur_cibleID = u.utilisateurID;

-- Vue des modérateurs sur les signalements d'une video
CREATE VIEW VueModo_Signalement_Videos AS
SELECT v.url_video, v.titre, s.raison, s.date_signalement, s.statut, s.pseudo_signaleur AS Signaleur
FROM Signalements s, Utilisateurs u, Videos v
WHERE s.videoID IS NOT NULL AND s.videoID = v.videoID ;

-- Vue des modérateurs sur les signalements d'un live
CREATE VIEW VueModo_Signalement_Lives AS
SELECT l.url_live, l.titre, s.raison, s.date_signalement, s.statut, s.pseudo_signaleur AS Signaleur
FROM Signalements s, Utilisateurs u, Lives l
WHERE s.liveID IS NOT NULL AND s.liveID = l.liveID;

-- Vue des modérateurs sur les signalements de commentaire sur une vidéo
CREATE VIEW VueModo_Signalement_CommentairesVideos AS
SELECT c.commentaireID, c.contenu, s.raison, s.date_signalement, s.statut, s.pseudo_signaleur AS Signaleur
FROM Signalements s, Utilisateurs u, CommentairesVideos c
WHERE s.commentaire_videoID IS NOT NULL AND s.commentaire_videoID = c.commentaireID;

-- Vue des modérateurs sur les signalements de commentaire sur un live
CREATE VIEW VueModo_Signalement_CommentairesLives AS
SELECT c.commentaireID, c.contenu, s.raison, s.date_signalement, s.statut, s.pseudo_signaleur AS Signaleur
FROM Signalements s, Utilisateurs u, CommentairesLives c
WHERE s.commentaire_liveID IS NOT NULL AND s.commentaire_liveID = c.commentaireID;

-- Vue des notifications d'un utilisateur
CREATE VIEW VueNotification_Utilisateur AS
SELECT n.date_notif, n.contenu, n.type_notification
FROM Notifications n, Utilisateurs u
WHERE n.utilisateurID = u.utilisateurID AND u.pseudo = USER;

-- Vue des videos des playlists de l'utilisateur
CREATE VIEW Vue_PlaylistVideo_Utilisateur AS
SELECT  pv.ordre, v.titre AS Titre_Video
FROM Utilisateurs u, Playlists p, PlaylistsVideos pv, Videos v
WHERE u.utilisateurID = p.utilisateurID AND u.pseudo = USER AND p.playlistID = pv.playlistID AND v.videoID = pv.videoID
ORDER BY pv.ordre ASC;

-- Vue des utilisateurs bloqués par l'utilisateur
CREATE View Vue_Utilisateur_Bloquer AS
SELECT T.pseudo, b.date_bloquage
FROM Utilisateurs u, BloquageUtilisateurs b, (SELECT pseudo, utilisateurID FROM Utilisateurs) T
WHERE u.pseudo = USER AND u.utilisateurID = b.utilisateur_bloqueur_ID AND T.utilisateurID = b.utilisateur_bloque_ID;

-- Vue des recommendations faite a un utilisateur
CREATE View Vue_Recommendation AS
SELECT v.titre, r.date_suggestion, r.type_suggestion
FROM Recommendations r, Utilisateurs u, Videos v
WHERE r.utilisateurID = u.utilisateurID AND pseudo = USER AND v.videoID = r.videoID;


